"""Source files of the main segment that are libultra 2.0J objects, built from decompals/ultralib.

  gen_libultra.py            -> build/libultra.mk (make rules) from tools/hh/libultra.json
  gen_libultra.py --stubs    also (re)write the src/<file>.c stubs that mark those files

tools/hh/libultra.json maps "main/<file>" to its ultralib source and the flags ultralib's ido.mk uses for it
(IDO 5.3, libultra_rom, version J). Those files aren't C from the registry: srcbuild leaves them alone, and the
progress report counts their functions as matched (the object is built straight from ultralib's source).
"""
import json, os, sys
HH = os.path.normpath(os.path.join(os.path.dirname(__file__), "../..")); os.chdir(HH)
LIB = json.load(open("tools/hh/libultra.json"))
FLAGS = ("-c -Wab,-r4300_mul -G 0 -nostdinc -Xcpluscomm -woff 516,649,838,712 -D_MIPS_SZLONG=32 -DF3DEX_GBI_2 "
         "-DBUILD_VERSION=VERSION_J -DBUILD_VERSION_STRING=\\\"2.0J\\\" -non_shared -D_FINALROM")
INC = "-I $(ULTRALIB_ABS)/include -I $(ULTRALIB_ABS)/include/compiler/ido -I $(ULTRALIB_ABS)/include/PR"
out = ["# generated by tools/hh/gen_libultra.py from tools/hh/libultra.json: libultra 2.0J objects built from ultralib",
       "ULTRALIB_ABS := $(abspath $(ULTRALIB))", ""]
for unit, e in sorted(LIB.items()):
    src = "$(ULTRALIB)/" + e["src"]
    out += ["$(BUILD)/src/%s.o: %s tools/hh/libultra.json" % (unit, src), "\t@mkdir -p $(dir $@)",
            "\t@cd $(dir %s) && $(abspath $(IDO53)) %s %s %s $(notdir %s) %s -o $(abspath $@)"
            % (src, FLAGS, e["mips"], e["opt"], src, INC), ""]
os.makedirs("build", exist_ok=True); open("build/libultra.mk", "w").write("\n".join(out))
if "--stubs" in sys.argv:
    for unit, e in LIB.items():
        open("src/%s.c" % unit, "w").write("/* libultra 2.0J: built from ultralib's %s (tools/hh/libultra.json) */\n" % e["src"])
print("libultra: %d files" % len(LIB))
