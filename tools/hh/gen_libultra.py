"""Source files of the main segment built from decompals/ultralib C.

  gen_libultra.py            -> build/libultra.mk (make rules) from tools/hh/libultra.json
  gen_libultra.py --stubs    also (re)write the src/<file>.c stubs that mark those files

tools/hh/libultra.json maps "main/<file>" to its ultralib source and the flags ultralib's ido.mk uses for it
(IDO 5.3, libultra_rom, default version J; optional version/flags/additional/storage fields). Those files aren't C from the registry: srcbuild leaves them alone, and the
progress report counts their functions as matched (the object is built straight from ultralib's source).
"""
import json, os, sys
HH = os.path.normpath(os.path.join(os.path.dirname(__file__), "../..")); os.chdir(HH)
LIB = json.load(open("tools/hh/libultra.json"))
# files whose ultralib object doesn't reproduce the ROM (and why): never put these back in libultra.json
EXCLUDED = json.load(open("tools/hh/libultra_excluded.json")) if os.path.exists("tools/hh/libultra_excluded.json") else {}
assert not set(LIB) & set(EXCLUDED), "libultra.json lists an excluded file: %s" % (set(LIB) & set(EXCLUDED))
FLAGS = ("-c -Wab,-r4300_mul -G 0 -nostdinc -Xcpluscomm -woff 516,649,838,712 -D_MIPS_SZLONG=32 -DF3DEX_GBI_2 "
         "-DBUILD_VERSION=VERSION_J -DBUILD_VERSION_STRING=\\\"2.0J\\\" -non_shared -D_FINALROM")
INC = "-I $(ULTRALIB_ABS)/include -I $(ULTRALIB_ABS)/include/compiler/ido -I $(ULTRALIB_ABS)/include/PR"
out = ["# generated by tools/hh/gen_libultra.py from tools/hh/libultra.json: SDK C objects built from ultralib",
       "ULTRALIB_ABS := $(abspath $(ULTRALIB))", ""]
for unit, e in sorted(LIB.items()):
    # Some inferred game units contain several complete SDK objects. Compile
    # them separately with their own flags, then concatenate via a normal
    # relocatable link; no source/instruction rewriting is involved.
    parts = [e] + e.get("additional", [])
    deps = " ".join("$(ULTRALIB)/" + part["src"] for part in parts)
    out += ["$(BUILD)/src/%s.o: %s tools/hh/libultra.json" % (unit, deps), "\t@mkdir -p $(dir $@)"]
    for index, part in enumerate(parts):
        src = "$(ULTRALIB)/" + part["src"]
        version = part.get("version", e.get("version", "J"))
        flags = FLAGS.replace("VERSION_J", "VERSION_" + version).replace("2.0J", "2.0" + version)
        target = "$(abspath $@)" if len(parts) == 1 else "$(abspath $@).part%d" % index
        out += [
            "\t@cd $(dir %s) && $(abspath $(IDO53)) %s %s %s $(notdir %s) %s -o $(abspath $@)"
             .replace("$(abspath $@)", target)
             % (src, flags + " " + part.get("flags", e.get("flags", "")), part.get("mips", e["mips"]), part.get("opt", e["opt"]), src, INC)]
        if "-mips3" in part.get("mips", e["mips"]):   # as ultralib does: mark the -mips3 object o32 again
            out.append("\t@$(PYTHON) $(ULTRALIB)/tools/set_o32abi_bit.py " + target)
    if len(parts) > 1:
        objects = " ".join("$@.part%d" % i for i in range(len(parts)))
        # GNU ld cannot merge IDO's optional GP-size bookkeeping when only
        # one input has .data. -G0 makes it irrelevant; retain all allocatable
        # code/data and relocations, dropping only these non-allocated tables
        # and ECOFF debug records (whose merge crashes GNU ld 2.40).
        for index in range(len(parts)):
            out.append("\t@$(OBJCOPY) --remove-section=.gptab.data --remove-section=.gptab.bss --remove-section=.mdebug $@.part%d" % index)
        out += ["\t@$(LD) -r -o $@ " + objects, "\t@rm " + objects]
    out.append("")
os.makedirs("build", exist_ok=True); open("build/libultra.mk", "w").write("\n".join(out))
if "--stubs" in sys.argv:
    for unit, e in LIB.items():
        sources = ", ".join(part["src"] for part in [e] + e.get("additional", []))
        version = e.get("version", "J")
        open("src/%s.c" % unit, "w").write("/* libultra 2.0%s: built from ultralib's %s (tools/hh/libultra.json) */\n" % (version, sources))
print("libultra: %d files" % len(LIB))
